#!/usr/bin/env node
/**
 * Generate js/sahaba-index.js from js/sahaba-data.js.
 *
 *   node tools/build-sahaba-index.js [--check]
 *
 * The dashboard's "Companion of the day" card needs a name, a role, an initial
 * and a colour for one companion — not the 576 KB dataset that the Sahaba tab
 * loads on demand. Before this index existed the card silently rendered
 * nothing unless the reader had already opened the Sahaba tab in that session.
 * Same pattern as tools/build-hope-index.js; --check fails on drift.
 */
const { fs, path, ROOT, load, get } = require('../tests/lib.js');
const rows = (get(load('js/sahaba-data.js'), 'SAHABA_DATA') || []).map((c) => ({
  id: c.id, en: c.en, bn: c.bn, roleEn: c.roleEn, roleBn: c.roleBn, init: c.init, color: c.color,
}));
const out = `/**
 * GENERATED by tools/build-sahaba-index.js — do not hand-edit.
 *
 * Card-sized metadata for every companion in js/sahaba-data.js, so the
 * dashboard can surface one without downloading the module. Full records live
 * in sahaba-data.js and are fetched only when the reader opens the tab.
 */
var SAHABA_INDEX = [
${rows.map((r) => '  ' + JSON.stringify(r)).join(',\n')}
];
`;
const OUT = path.join(ROOT, 'js/sahaba-index.js');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== out) { console.error('js/sahaba-index.js is stale — run: node tools/build-sahaba-index.js'); process.exit(1); }
  console.log(`sahaba-index.js is current: ${rows.length} companions`); process.exit(0);
}
fs.writeFileSync(OUT, out);
console.log(`wrote js/sahaba-index.js — ${rows.length} companions, ${(out.length / 1024).toFixed(1)} KB`);
