#!/usr/bin/env node
/**
 * Generate js/hope-index.js from js/hope-data.js.
 *
 *   node tools/build-hope-index.js
 *
 * WHY THIS EXISTS. js/hope-data.js is ~400 KB and is lazily loaded when the
 * Hope tab is opened. The dashboard is the landing tab and wants to show one
 * rotating chapter on it; pulling the whole module on every cold start to
 * render a title and a tagline would undo the entire point of lazy loading.
 *
 * So this writes the minimum a card needs — id, wing, emoji, title, tagline and
 * the chapter's first verse reference — for all chapters. The result is a few
 * KB, ships eagerly, and the full chapter is still only fetched when the reader
 * actually opens it. Same trick as tools/build-article-index.js.
 *
 * Regenerate after ANY change to chapter ids, titles or taglines.
 * tests/check-hope-index.js fails the build if this was forgotten.
 */
const { ROOT, fs, path, load, get } = require('../tests/lib.js');

const sb = load('js/hope-data.js');
const chapters = get(sb, 'HOPE_CHAPTERS') || [];
if (!chapters.length) { console.error('HOPE_CHAPTERS is empty — refusing to write an empty index'); process.exit(1); }

const rows = chapters.map((c) => ({
  id: c.id,
  wing: c.wing,
  emoji: c.emoji,
  title: { en: c.title.en, bn: c.title.bn },
  tagline: { en: c.tagline.en, bn: c.tagline.bn },
  ref: (c.verses && c.verses[0] && c.verses[0].ref) || '',
}));

const body = rows.map((r) => '  ' + JSON.stringify(r)).join(',\n');
const out = `/**
 * GENERATED by tools/build-hope-index.js — do not hand-edit.
 *
 * Card-sized metadata for every chapter in js/hope-data.js, so the dashboard
 * and the welcome tour can surface a chapter without downloading the module.
 * Full chapter content (verses, hadith, du'a, practice) lives in hope-data.js
 * and is fetched only when the reader opens the tab.
 */
const HOPE_INDEX = [
${body}
];
`;
fs.writeFileSync(path.join(ROOT, 'js/hope-index.js'), out);
console.log(`wrote js/hope-index.js — ${rows.length} chapters, ${(out.length / 1024).toFixed(1)} KB`);
