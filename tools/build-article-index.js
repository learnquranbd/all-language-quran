#!/usr/bin/env node
/**
 * Regenerate js/article-index.js from the article files.
 *
 *   node tools/build-article-index.js [--check]
 *
 * The index answers one question cheaply: does subject X have a long-form
 * article? Without it a view cannot know whether to offer a "read the full
 * article" control until it has already downloaded the articles — which is the
 * very thing that must stay on demand. The Tadabbur tab renders 299 cards in
 * one pass, so guessing would mean 299 dead controls or 299 useless fetches.
 *
 * Generated, never hand-edited: `--check` fails if it has drifted from the
 * article files, and `npm test` runs that check.
 */
const { fs, path, ROOT, load, get, loadTadabburArticles } = require('../tests/lib.js');

const SETS = [
  ['prophets', 'js/prophets-articles.js', 'PROPHET_ARTICLES'],
  ['sahaba', 'js/sahaba-articles.js', 'SAHABA_ARTICLES'],
  ['tadabbur', null, null, loadTadabburArticles],   // sharded per surah
];
const OUT = path.join(ROOT, 'js/article-index.js');

const index = {};
for (const [key, file, obj, loader] of SETS) {
  if (!loader && !fs.existsSync(path.join(ROOT, file))) { index[key] = []; continue; }
  const table = loader ? loader() : (get(load(file), obj) || {});
  index[key] = Object.keys(table)
    .filter((id) => table[id] && Array.isArray(table[id].sections) && table[id].sections.length)
    .sort();
}

const body = `/**
 * Which subjects have a long-form article — GENERATED by
 * tools/build-article-index.js. Do not edit by hand; \`npm test\` fails on drift.
 *
 * A view needs this to decide whether to offer a "full article" control without
 * first downloading the articles themselves, which are large and deliberately
 * fetched only when a reader asks for one.
 */

/* \`var\`, not \`const\`: js/article-view.js reads window.LQ_ARTICLE_IDS, and a
 * top-level const in a classic script is not a window property. */
var LQ_ARTICLE_IDS = ${JSON.stringify(index, null, 2)};

if (typeof module !== 'undefined' && module.exports) module.exports = { LQ_ARTICLE_IDS };
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error('article-index.js is stale — run: node tools/build-article-index.js');
    process.exit(1);
  }
  console.log('article-index.js is current: ' + SETS.map(([k]) => `${k} ${index[k].length}`).join(', '));
  process.exit(0);
}

fs.writeFileSync(OUT, body);
console.log('wrote js/article-index.js: ' + SETS.map(([k]) => `${k} ${index[k].length}`).join(', '));
